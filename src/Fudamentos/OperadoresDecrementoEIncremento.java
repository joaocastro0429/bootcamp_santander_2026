package Fudamentos;

public class OperadoresDecrementoEIncremento {
    public static void main(String[] args) {
        int numero = 10;

        numero++;

        System.out.println(numero);


        numero--;
        System.out.println(numero);

        // Pos incremento

        int x = 5;

        System.out.println(x++);
        System.out.println(x);
    }
}
