package Fudamentos;

public class OperadoresRelacionais {
    public static void main(String[] args) {
        int numero=5;
        int numero2=6;

        System.out.println(numero > numero2);
        System.out.println(numero < numero2);
        System.out.println(numero >= numero2);
        System.out.println(numero <= numero2);
        System.out.println(numero==numero2);
        System.out.println(numero2!=numero2);
    }
}
