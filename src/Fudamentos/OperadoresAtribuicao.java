package Fudamentos;

public class OperadoresAtribuicao {
    public static void main(String[] args) {
        int numero=5;

        System.out.println(numero+=5);
        System.out.println(numero-=5);
        System.out.println(numero*=5);
        System.out.println(numero/=5);
        System.out.println(numero%=5);
    }
}
